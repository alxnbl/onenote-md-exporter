using alxnbl.OneNoteMdExporter.Models;
using Microsoft.Extensions.Configuration;

namespace alxnbl.OneNoteMdExporter.Infrastructure
{
    public class AppSettings
    {

        /*
          * Export general settings
          * */

        /// <summary>
        /// Maximum number of characters of a page title. Among this limit, title is contracted.
        /// </summary>
        public static int PageTitleMaxLength { get; set; } = 50;

        /// <summary>
        /// Add at the beginning of each page a YAML header that include Page metadata (cf https://assemble.io/docs/YAML-front-matter.html)
        /// </summary>
        public static bool AddFrontMatterHeader { get; set; } = true;

        /// <summary>
        /// Front Matter date format https://learn.microsoft.com/en-us/dotnet/standard/base-types/custom-date-and-time-format-strings
        /// </summary>
        public static string FrontMatterDateFormat { get; set; } = "yyyy-MM-ddTHH:mm:ss";

        /// <summary>
        /// Length limit of Section and page name used in file and folder name. Reduce this value to avoid error of max file system file path
        /// </summary>
        public static int MdMaxFileLength { get; set; } = 50;

        /// <summary>
        /// How page hierarchies should be exported :
        /// - HierarchyAsFolderTree : add folder tree to store pages
        /// - HierarchyAsPageTitlePrefix : prefix page title with their parent / grand-parent page name
        /// - IgnoreHierarchy : ignore page hierarchy
        /// Apply to : Markdown Format
        /// </summary>
        public static PageHierarchyEnum ProcessingOfPageHierarchy { get; set; } = PageHierarchyEnum.HierarchyAsFolderTree;

        /// <summary>
        /// For MdExport with ProcessingOfPageHierarchy=hierarchyAsPageTitlePrefix, the separator to use to prefix md page file name
        /// Ex: "_" value for "ParentPage_ChildPage.md"
        /// </summary>
        public static string PageHierarchyFileNamePrefixSeparator { get; set; } = "_";

        /// <summary>
        /// Copy DocX export of pages along md files, keep temporary OneNote notebook opened
        /// </summary>
        public static bool KeepOneNoteTempFiles { get; set; } = false;

        /// <summary>
        /// Where file attachments and image files should me stored ?
        /// - RootFolder : in a single folder at the root of the export folder,
        /// - PageParentFolder : in folders next to the md file
        /// Apply to : Markdown Format
        /// </summary>
        public static ResourceFolderLocationEnum ResourceFolderLocation { get; set; } = ResourceFolderLocationEnum.RootFolder;

        /// <summary>
        /// Name of the resource folder where attachments and image files are stored
        /// </summary>
        public static string ResourceFolderName { get; set; } = "_resources";

        /// <summary>
        /// OneNote indentation handling
        /// </summary>
        public static IndentingStyleEnum IndentingStyle { get; set; } = IndentingStyleEnum.ConvertToBullets;
        

        /*
         * Markdown rendering Settings
         * */

        /// <summary>
        /// One of pandoc format https://pandoc.org/MANUAL.html#general-options
        /// Rq: For Joplin "gfm" is recommended
        /// </summary>
        public static string PanDocMarkdownFormat { get; set; } = "gfm";

        /// <summary>
        /// Convert HTML IMG tag generated by PanDoc into markdown references
        /// </summary>
        public static bool PostProcessingMdImgRef { get; set; } = true;

        /// <summary>
        /// Remove undesired quotation blocks sometimes generated by PanDoc
        /// </summary>
        public static bool PostProcessingRemoveQuotationBlocks { get; set; } = true;

        /// <summary>
        /// Remove OneNote header generated by OneNote Export APIs
        /// </summary>
        public static bool PostProcessingRemoveOneNoteHeader { get; set; } = true;

        /// <summary>
        /// Replace every pair of linebreak by a single linebreak (to avoid duplicates generated by Pandoc)
        /// </summary>
        public static bool DeduplicateLinebreaks { get; set; } = true;

        /// <summary>
        /// Prevent generation of more that 2 linebreaks in a row
        /// </summary>
        public static bool MaxTwoLineBreaksInARow { get; set; } = true;

        /// <summary>
        /// Capture HTML styling in span-elements and "escape" it, so it is preserved during translation.
        /// This is useful for editors like TipTap/Notesnook that can handle HTML.
        /// NB: This means highlighting is not translated into markdown highlighting using '=='.
        /// </summary>
        public static bool UseHtmlStyling { get; set; } = true;

        /// <summary>
        /// OneNote links handling
        /// </summary>
        public static OneNoteLinksHandlingEnum OneNoteLinksHandling { get; set; } = OneNoteLinksHandlingEnum.ConvertToMarkdown;


        /// <summary>
        /// ADVANCED SETTING : Disable transformation based on OneNote XML preprocessing (paraph unfold, background and font-color,...)
        /// </summary>
        public static bool DisablePageXmlPreProcessing { get; set; } = false;

        /// <summary>
        /// ADVANCED SETTING (Markdown export): when the OneNote -> Word -> PanDoc route produces no content
        /// for a page, render that page's Markdown straight from its OneNote XML instead of leaving it empty.
        /// Only acts on pages the normal route failed to render, so it never changes a page that already has
        /// content. Set to false to keep the previous behaviour (empty page).
        /// </summary>
        public static bool XmlFallbackRenderer { get; set; } = true;

        /// <summary>
        /// ADVANCED SETTING (Markdown export): a fixed export root folder (set by --output). When empty, each
        /// export goes to a new timestamped folder under "Exports" (the default). When set, the notebook is
        /// always exported to the same folder, which is what makes --resume able to continue it.
        /// </summary>
        public static string ExportRootFolder { get; set; } = "";

        /// <summary>
        /// ADVANCED SETTING (Markdown export, needs ExportRootFolder / --output): continue an interrupted
        /// export in that folder -- skip the pages already recorded in the notebook's export journal and
        /// export the rest -- instead of cleaning the folder and starting over.
        /// </summary>
        public static bool ResumeExport { get; set; } = false;

        /// <summary>
        /// ADVANCED SETTING (Markdown export, needs Word/Excel/PowerPoint installed): make a PDF copy of each
        /// Office file attachment (.docx, .xlsx, .pptx, …) next to it and link it under the attachment, so the
        /// content stays readable without Office. The original file is always kept. Default false.
        /// </summary>
        public static bool ConvertOfficeToPdf { get; set; } = false;

        /// <summary>
        /// ADVANCED SETTING: restrict ConvertOfficeToPdf to these extensions (e.g. [".docx", ".pptx"]). Empty = all
        /// supported Office formats.
        /// </summary>
        public static string[] OfficeToPdfExtensions { get; set; } = System.Array.Empty<string>();

        /// <summary>
        /// ADVANCED SETTING: timeout in seconds for a single Office-to-PDF conversion. A conversion that does not
        /// finish in time is abandoned and its Office instance killed, so one bad file cannot hang the export.
        /// Also the base timeout for ffmpeg media conversions (multiplied for the longer media runs).
        /// </summary>
        public static int ConversionTimeoutSeconds { get; set; } = 180;

        /// <summary>
        /// ADVANCED SETTING: path to ffmpeg (used for media copies and transcription). "ffmpeg" finds it on PATH
        /// (or the registry PATH / winget links). All media features are skipped when ffmpeg is not found.
        /// </summary>
        public static string FfmpegPath { get; set; } = "ffmpeg";

        /// <summary>
        /// ADVANCED SETTING (Markdown export, needs ffmpeg): audio attachment extensions to also copy as MP3 next
        /// to the original (e.g. [".wma"]). Empty = no audio conversion (the default).
        /// </summary>
        public static string[] AudioToMp3Extensions { get; set; } = System.Array.Empty<string>();

        /// <summary>
        /// ADVANCED SETTING (Markdown export, needs ffmpeg): video attachment extensions to also copy as MP4 next
        /// to the original (e.g. [".wmv"]). Empty = no video conversion (the default).
        /// </summary>
        public static string[] VideoToMp4Extensions { get; set; } = System.Array.Empty<string>();

        /// <summary>
        /// ADVANCED SETTING (needs ffmpeg): command line to transcribe a media attachment. {input} is a 16 kHz
        /// mono WAV ffmpeg prepares, {output} is the transcript path stem; the tool must write &lt;stem&gt;.txt. Empty
        /// = no transcription (the default). Example: whisper-cli -m model.bin -f {input} -otxt -of {output}
        /// </summary>
        public static string TranscriptionCommand { get; set; } = "";

        /// <summary>
        /// ADVANCED SETTING (Markdown export): convert EMF/WMF metafile attachments and images to PNG, which
        /// Markdown viewers can display, and reference the PNG instead. Also render XPS printout attachments to
        /// one PNG per page, embedded under the attachment. The originals are always kept. Set to false to leave
        /// metafiles and XPS untouched (they will not render in most viewers).
        /// </summary>
        public static bool ConvertLegacyFormats { get; set; } = true;

        /// <summary>
        /// ADVANCED SETTING: resolution in DPI used to render XPS printout attachments to PNG (ConvertLegacyFormats).
        /// </summary>
        public static int XpsRenderDpi { get; set; } = 150;

        /// <summary>
        /// ADVANCED SETTING (Markdown export): write an "_index.md" in each section folder listing its pages in
        /// OneNote order (indented by page level), and one at the notebook root listing its sections. Default false.
        /// </summary>
        public static bool WriteIndexNotes { get; set; } = false;

        /// <summary>
        /// ADVANCED SETTING (Markdown export): resolve links between exported pages. Links to other OneNote pages
        /// are written as placeholders during export and, after the whole run, rewritten to plain relative links
        /// that work in any tool — so a link to a page exported later (another notebook, a sub-page) is not lost.
        /// Default false (links to pages not yet exported are dropped, as before).
        /// </summary>
        public static bool RepairLinks { get; set; } = false;

        /// <summary>
        /// ADVANCED SETTING (Markdown export): a clean-up pass on the generated markdown — unescape the "\&lt;" /
        /// "\&gt;" PanDoc emits, unwrap default-style and empty span noise from pasted Outlook/Word content, and
        /// renumber ordered lists PanDoc writes as "1. 1. 1.". Fenced code blocks are left untouched. Default false.
        /// </summary>
        public static bool MarkdownCleanup { get; set; } = false;

        /// <summary>
        /// ADVANCED SETTING (Markdown export): maximum full path length of an exported page file. A page whose
        /// path would be longer is shortened (its file name is cut and a short hash keeps it unique), and if the
        /// folder alone is already too long the page is written to a "_long-paths" folder at the root of the
        /// notebook folder. Room is reserved for the resources folder and attachment file names. 0 disables the
        /// guard (the default). The classic Windows path limit is 260.
        /// </summary>
        public static int MaxPathLength { get; set; } = 0;

        /*
         * Developer Settings
         * */

        /// <summary>
        /// Enable verbose mode and keep temporary files (.docx)
        /// </summary>
        public static bool Debug { get; set; } = false;


        public static void LoadAppSettings()
        {
            new ConfigurationBuilder()
                .AddJsonFile("appSettings.json")
                .Build()
                .Get<AppSettings>();
        }
    }
}
